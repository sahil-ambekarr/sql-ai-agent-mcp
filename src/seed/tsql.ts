import { generateSampleData, type SampleData } from './generate.ts';
import { TABLES, tsqlDdl } from './schema.ts';

function lit(v: unknown): string {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  return `N'${String(v).replace(/'/g, "''")}'`;
}

/**
 * Renders the full T-SQL seed script: database, tables, data, and a
 * least-privilege login for the MCP server. Uses sqlcmd variables
 * $(DB_NAME) and $(READER_PASSWORD) so no secret lives in the file.
 */
export function renderTsqlSeed(data: SampleData = generateSampleData()): string {
  const out: string[] = [];
  out.push('-- Generated by `npm run seed:mssql-script` from src/seed/generate.ts. Do not edit by hand.');
  out.push('-- Run with sqlcmd: -v DB_NAME=SampleBusiness READER_PASSWORD=...');
  out.push('SET NOCOUNT ON;');
  out.push("IF DB_ID(N'$(DB_NAME)') IS NULL CREATE DATABASE [$(DB_NAME)];");
  out.push('GO');
  out.push('USE [$(DB_NAME)];');
  out.push('GO');
  for (const t of [...TABLES].reverse()) out.push(`IF OBJECT_ID(N'dbo.${t.name}', N'U') IS NOT NULL DROP TABLE dbo.${t.name};`);
  out.push('GO');
  for (const t of TABLES) {
    out.push(tsqlDdl(t));
    out.push('GO');
    const cols = t.columns.map((c) => c.name);
    const rows = data[t.name as keyof SampleData] as unknown as Array<Record<string, unknown>>;
    // T-SQL allows at most 1000 rows per VALUES list.
    for (let i = 0; i < rows.length; i += 500) {
      const chunk = rows.slice(i, i + 500);
      out.push(`INSERT INTO dbo.${t.name} (${cols.join(', ')}) VALUES`);
      out.push(chunk.map((r) => `(${cols.map((c) => lit(r[c])).join(', ')})`).join(',\n') + ';');
      out.push('GO');
    }
  }
  out.push('CREATE INDEX ix_orders_customer ON dbo.orders(customer_id);');
  out.push('CREATE INDEX ix_orders_date ON dbo.orders(order_date);');
  out.push('CREATE INDEX ix_items_order ON dbo.order_items(order_id);');
  out.push('CREATE INDEX ix_items_product ON dbo.order_items(product_id);');
  out.push('CREATE INDEX ix_tickets_customer ON dbo.support_tickets(customer_id);');
  out.push('GO');
  out.push('-- Least-privilege login used by the MCP server: read only, explicit DENY on writes.');
  out.push("IF SUSER_ID(N'agent_reader') IS NULL CREATE LOGIN agent_reader WITH PASSWORD = N'$(READER_PASSWORD)', CHECK_POLICY = ON;");
  out.push("IF USER_ID(N'agent_reader') IS NULL CREATE USER agent_reader FOR LOGIN agent_reader;");
  out.push('ALTER ROLE db_datareader ADD MEMBER agent_reader;');
  out.push('DENY INSERT, UPDATE, DELETE, ALTER, EXECUTE, REFERENCES ON SCHEMA::dbo TO agent_reader;');
  out.push('DENY CREATE TABLE, CREATE VIEW, CREATE PROCEDURE, CREATE FUNCTION TO agent_reader;');
  out.push('GO');
  return out.join('\n') + '\n';
}
